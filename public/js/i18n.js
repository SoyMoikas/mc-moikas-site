function detect() {
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "en" || saved === "es") return saved;
  } catch { /* storage blocked */ }
  return (navigator.languages || [navigator.language || "en"]).some((l) => String(l).toLowerCase().startsWith("es")) ? "es" : "en";
}

export const lang = detect();
export const locale = lang === "es" ? "es-MX" : "en-US";
document.documentElement.lang = lang;

export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

// Translate an error message from the API if we know it.
export function tErr(msg) {
  const k = `err.${msg}`;
  return STRINGS[lang][k] ?? msg;
}

export function setLang(l) {
  try { localStorage.setItem("lang", l); } catch { /* ignore */ }
  location.reload();
}

// Static text in HTML: <h2 data-i18n="home.servers">Servers</h2>
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
}
